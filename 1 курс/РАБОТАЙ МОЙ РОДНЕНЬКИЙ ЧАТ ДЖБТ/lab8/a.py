import pandas as pd
import io

# Исходные данные от пользователя
data = """Бортовой номер,Уровень топлива/заряда (%),Текущие координаты,Пробег,Дата последнего ТО,Статус
CS-1042, 45.2, "55.7558,37.6173", 12050, 2025-11-15, Свободен
CS- 0023, 88.0, "55.8000,37.6000", 8900, 2026-01-10, Арендован
CS-5511 ,12.5, "55.6000,37.5000", 15000, 2025-12-01, Сервис
CS-8899,67.3, "55.7100,37.6500", 5400, 2026-02-20, Свободен
CS-3341, 99.1, "55.8500,37.4500", 2100, 2026-03-05, Арендован"""

# Чтение данных с автоматическим удалением начальных пробелов после разделителей
df = pd.read_csv(io.StringIO(data), skipinitialspace=True)

# Дополнительная очистка текстовых полей от лишних пробелов на краях
for col in df.select_dtypes(include=['object']).columns:
    df[col] = df[col].astype(str).str.strip()

# Сохранение в CSV-файл с кодировкой utf-8-sig (чтобы корректно открывалось в Excel)
file_name = 'fleet_status.csv'
df.to_csv(file_name, index=False, encoding='utf-8-sig')
print(f"Generated file: {file_name}")